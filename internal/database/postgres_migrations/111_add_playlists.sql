-- Playlists made with an AI assistant, and their copies on Jellyfin, Plex,
-- Spotify and YouTube Music. A link is one copy: for Jellyfin and Plex it
-- names a media server and an account on it; remote_id is empty until the
-- first sync creates the playlist there.
CREATE TABLE playlists (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    request TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE playlist_tracks (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    playlist_id INTEGER NOT NULL REFERENCES playlists(id) ON DELETE CASCADE,
    position INTEGER NOT NULL,
    artist TEXT NOT NULL,
    title TEXT NOT NULL,
    album TEXT NOT NULL DEFAULT ''
);

CREATE INDEX idx_playlist_tracks_playlist ON playlist_tracks(playlist_id, position);

CREATE TABLE playlist_links (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    playlist_id INTEGER NOT NULL REFERENCES playlists(id) ON DELETE CASCADE,
    service TEXT NOT NULL CHECK (service IN ('jellyfin', 'plex', 'spotify', 'ytmusic')),
    server_id INTEGER REFERENCES media_servers(id) ON DELETE CASCADE,
    account_id TEXT NOT NULL DEFAULT '',
    account_name TEXT NOT NULL DEFAULT '',
    remote_id TEXT NOT NULL DEFAULT '',
    remote_name TEXT NOT NULL DEFAULT '',
    matched INTEGER NOT NULL DEFAULT 0,
    missing INTEGER NOT NULL DEFAULT 0,
    message TEXT NOT NULL DEFAULT '',
    last_synced_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_playlist_links_playlist ON playlist_links(playlist_id);
CREATE INDEX idx_playlist_links_server ON playlist_links(server_id);

-- Spotify and YouTube Music sign-ins. settings_encrypted holds a JSON object:
-- the Spotify client ID, secret and refresh token, or the YouTube Music
-- browser cookie.
CREATE TABLE playlist_services (
    service TEXT PRIMARY KEY CHECK (service IN ('spotify', 'ytmusic')),
    settings_encrypted TEXT NOT NULL,
    account_name TEXT NOT NULL DEFAULT '',
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
