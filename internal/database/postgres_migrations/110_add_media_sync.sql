-- Watched-state sync between media servers (Jellyfin, Plex). A pair links two
-- servers with a direction; user maps say which account on one server is which
-- account on the other; runs and run items are the sync log.
CREATE TABLE media_servers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type TEXT NOT NULL CHECK (type IN ('jellyfin', 'plex')),
    name TEXT NOT NULL,
    base_url TEXT NOT NULL,
    token_encrypted TEXT NOT NULL,
    enabled INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE media_sync_pairs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    server_a_id INTEGER NOT NULL REFERENCES media_servers(id) ON DELETE CASCADE,
    server_b_id INTEGER NOT NULL REFERENCES media_servers(id) ON DELETE CASCADE,
    direction TEXT NOT NULL CHECK (direction IN ('both', 'a_to_b', 'b_to_a')),
    enabled INTEGER NOT NULL DEFAULT 1,
    interval_minutes INTEGER NOT NULL DEFAULT 60,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (server_a_id <> server_b_id)
);

CREATE INDEX idx_media_sync_pairs_server_a ON media_sync_pairs(server_a_id);
CREATE INDEX idx_media_sync_pairs_server_b ON media_sync_pairs(server_b_id);

CREATE TABLE media_sync_user_maps (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pair_id INTEGER NOT NULL REFERENCES media_sync_pairs(id) ON DELETE CASCADE,
    user_a_id TEXT NOT NULL,
    user_a_name TEXT NOT NULL,
    user_b_id TEXT NOT NULL,
    user_b_name TEXT NOT NULL,
    UNIQUE (pair_id, user_a_id, user_b_id)
);

CREATE TABLE media_sync_runs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pair_id INTEGER NOT NULL REFERENCES media_sync_pairs(id) ON DELETE CASCADE,
    source TEXT NOT NULL,
    status TEXT NOT NULL,
    users INTEGER NOT NULL DEFAULT 0,
    marked_a INTEGER NOT NULL DEFAULT 0,
    marked_b INTEGER NOT NULL DEFAULT 0,
    failed INTEGER NOT NULL DEFAULT 0,
    not_found INTEGER NOT NULL DEFAULT 0,
    message TEXT NOT NULL DEFAULT '',
    started_at TIMESTAMP NOT NULL,
    finished_at TIMESTAMP
);

CREATE INDEX idx_media_sync_runs_pair_started ON media_sync_runs(pair_id, started_at);
CREATE INDEX idx_media_sync_runs_started ON media_sync_runs(started_at);

CREATE TABLE media_sync_run_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id INTEGER NOT NULL REFERENCES media_sync_runs(id) ON DELETE CASCADE,
    user_name TEXT NOT NULL,
    target TEXT NOT NULL CHECK (target IN ('a', 'b')),
    title TEXT NOT NULL,
    error TEXT NOT NULL DEFAULT ''
);

CREATE INDEX idx_media_sync_run_items_run ON media_sync_run_items(run_id);
